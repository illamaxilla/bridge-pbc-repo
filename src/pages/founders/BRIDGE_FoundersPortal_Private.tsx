// ─── Markdown renderer ────────────────────────────────────────────────────────
const MD = ({ text, streaming=false }) => {
  // During streaming: complete any unclosed ** so partial tokens don't show raw
  const safeText = streaming
    ? text.replace(/\*\*(?![^*]*\*\*)([^*]*)$/, (_, partial) => `**${partial}**`)
    : text;

  // ── Inline renderer: bold, inline-code, italic ─────────────────────────────
  const inline = (str) => {
    if (!str) return null;
    // Split on **bold**, `code`, *italic* — process in one pass
    const re = /(\*\*([^*]+)\*\*|`([^`]+)`|\*([^*]+)\*)/g;
    const parts = [];
    let last = 0, m;
    while ((m = re.exec(str)) !== null) {
      if (m.index > last) parts.push(str.slice(last, m.index));
      if (m[2] !== undefined) {
        // **bold**
        parts.push(<strong key={m.index} style={{fontWeight:700,color:PAPER,fontFamily:Fs}}>{m[2]}</strong>);
      } else if (m[3] !== undefined) {
        // `code`
        parts.push(<code key={m.index} style={{fontFamily:Fm,fontSize:12,color:LIME,background:`${LIME}15`,padding:'1px 5px',borderRadius:2}}>{m[3]}</code>);
      } else if (m[4] !== undefined) {
        // *italic*
        parts.push(<em key={m.index} style={{fontStyle:'italic',color:MUTED}}>{m[4]}</em>);
      }
      last = m.index + m[0].length;
    }
    if (last < str.length) parts.push(str.slice(last));
    return parts.length > 0 ? parts : str;
  };

  // ── Tokeniser ──────────────────────────────────────────────────────────────
  const tokens = [];
  const lines = safeText.split('\n');
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const trim = line.trim();

    if (trim === '') { tokens.push({ type:'gap', key:i }); i++; continue; }
    if (/^-{3,}$/.test(trim)) { tokens.push({ type:'hr', key:i }); i++; continue; }

    // Headings — strip leading **/** from text before storing
    if (line.startsWith('#### ')) { tokens.push({ type:'h4', text:line.slice(5).replace(/\*\*/g,''), key:i }); i++; continue; }
    if (line.startsWith('### ')) { tokens.push({ type:'h3', text:line.slice(4).replace(/\*\*/g,''), key:i }); i++; continue; }
    if (line.startsWith('## '))  { tokens.push({ type:'h2', text:line.slice(3).replace(/\*\*/g,''), key:i }); i++; continue; }
    if (line.startsWith('# '))   { tokens.push({ type:'h1', text:line.slice(2).replace(/\*\*/g,''), key:i }); i++; continue; }

    // Blockquote
    if (line.startsWith('> ')) { tokens.push({ type:'bq', text:line.slice(2), key:i }); i++; continue; }

    // Bullet list — consume contiguous block
    if (/^[-*] /.test(line)) {
      const items = [];
      while (i < lines.length && /^[-*] /.test(lines[i])) {
        items.push(lines[i].replace(/^[-*] /, '')); i++;
      }
      tokens.push({ type:'ul', items, key:`ul${i}` }); continue;
    }

    // Numbered list — consume contiguous block
    if (/^\d+\. /.test(line)) {
      const items = [];
      while (i < lines.length && /^\d+\. /.test(lines[i])) {
        items.push(lines[i].replace(/^\d+\. /, '')); i++;
      }
      tokens.push({ type:'ol', items, key:`ol${i}` }); continue;
    }

    tokens.push({ type:'p', text:line, key:i }); i++;
  }

  // ── Renderer ───────────────────────────────────────────────────────────────
  return (
    <div style={{display:'flex',flexDirection:'column',gap:0}}>
      {tokens.map(tok => {
        switch (tok.type) {

          case 'gap':
            return <div key={tok.key} style={{height:10}}/>;

          case 'hr':
            return <div key={tok.key} style={{borderTop:`1px solid ${LINE}`,margin:'16px 0'}}/>;

          case 'h1':
            return (
              <div key={tok.key} style={{fontFamily:Fd,fontSize:18,fontWeight:700,color:PAPER,lineHeight:1.2,marginTop:18,marginBottom:8,paddingBottom:8,borderBottom:`1px solid ${LINE}`}}>
                {tok.text}
              </div>
            );

          case 'h2':
            return (
              <div key={tok.key} style={{fontFamily:Fs,fontSize:10,fontWeight:700,color:LIME,letterSpacing:'2.5px',textTransform:'uppercase',marginTop:20,marginBottom:8,display:'flex',alignItems:'center',gap:8}}>
                <div style={{width:16,height:2,background:LIME,flexShrink:0}}/>
                {tok.text}
              </div>
            );

          case 'h3':
            return (
              <div key={tok.key} style={{fontFamily:Fs,fontSize:13,fontWeight:700,color:PAPER,marginTop:14,marginBottom:5,paddingLeft:8,borderLeft:`2px solid ${TEAL}`}}>
                {tok.text}
              </div>
            );

          case 'h4':
            return (
              <div key={tok.key} style={{fontFamily:Fs,fontSize:11,fontWeight:700,color:MUTED,letterSpacing:'0.5px',marginTop:10,marginBottom:4}}>
                {tok.text}
              </div>
            );

          case 'bq':
            return (
              <div key={tok.key} style={{borderLeft:`2px solid ${LIME}`,paddingLeft:14,margin:'10px 0',background:`${LIME}06`,padding:'10px 14px',borderRadius:'0 2px 2px 0'}}>
                <div style={{fontFamily:Fb,fontSize:13.5,color:LIME,fontStyle:'italic',lineHeight:1.7}}>
                  {inline(tok.text)}
                </div>
              </div>
            );

          case 'ul':
            return (
              <div key={tok.key} style={{display:'flex',flexDirection:'column',gap:6,margin:'8px 0'}}>
                {tok.items.map((item, j) => (
                  <div key={j} style={{display:'flex',gap:12,alignItems:'flex-start'}}>
                    <div style={{width:5,height:5,borderRadius:'50%',background:LIME,marginTop:7,flexShrink:0}}/>
                    <div style={{fontFamily:Fb,fontSize:13.5,color:PAPER,lineHeight:1.75,flex:1}}>{inline(item)}</div>
                  </div>
                ))}
              </div>
            );

          case 'ol':
            return (
              <div key={tok.key} style={{display:'flex',flexDirection:'column',gap:6,margin:'8px 0'}}>
                {tok.items.map((item, j) => (
                  <div key={j} style={{display:'flex',gap:12,alignItems:'flex-start'}}>
                    <div style={{fontFamily:Fm,fontSize:11,fontWeight:700,color:LIME,minWidth:22,paddingTop:1,flexShrink:0,textAlign:'right'}}>{j+1}.</div>
                    <div style={{fontFamily:Fb,fontSize:13.5,color:PAPER,lineHeight:1.75,flex:1}}>{inline(item)}</div>
                  </div>
                ))}
              </div>
            );

          default: // paragraph
            return (
              <div key={tok.key} style={{fontFamily:Fb,fontSize:13.5,color:PAPER,lineHeight:1.82}}>
                {inline(tok.text)}
              </div>
            );
        }
      })}
    </div>
  );
};


