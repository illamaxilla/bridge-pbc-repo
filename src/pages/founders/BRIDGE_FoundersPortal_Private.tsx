// ─── Mobile card carousel with dot indicators ─────────────────────────────────
const MobCarousel = ({ items, renderItem, id }) => {
  const [idx, setIdx] = useState(0);
  const trackRef = useRef(null);
  const handleScroll = () => {
    if (!trackRef.current) return;
    const el = trackRef.current;
    const itemW = el.children[0]?.offsetWidth || 280;
    setIdx(Math.round(el.scrollLeft / (itemW + 10)));
  };
  return (
    <div className="mob-carousel">
      <div ref={trackRef} className="mob-carousel-track" onScroll={handleScroll}>
        {items.map((item, i) => (
          <div key={i}>{renderItem(item, i)}</div>
        ))}
      </div>
      <div className="mob-dots" style={{display:'none'}}>
        {items.map((_, i) => (
          <div key={i} style={{
            width: i===idx ? 18 : 6, height:6, borderRadius:3,
            background: i===idx ? LIME : FAINT,
            transition:'all 0.2s', cursor:'pointer',
          }} onClick={() => {
            const el = trackRef.current;
            if (!el) return;
            const itemW = el.children[0]?.offsetWidth || 280;
            el.scrollTo({ left: i * (itemW + 10), behavior:'smooth' });
          }}/>
        ))}
      </div>
    </div>
  );
};


